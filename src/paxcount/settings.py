# человека, вышедшего из-за перекрытия в стороне от места пропажи.
DEFAULT_PROXIMITY_THRESH = 0.5
DEFAULT_APPEARANCE_THRESH = 0.8


@dataclass(frozen=True)
class DetectorSettings:
    """Всё, что влияет на результат детекции, а значит и на ключ кэша."""

    weights: str = str(MODELS_DIR / "yolo11s.pt")
    imgsz: int = 960
    # botsort включает компенсацию движения камеры — нужна для съёмки с рук.
    tracker: str = "botsort.yaml"
    stride: int = 1
    conf: float = 0.25
    # Сколько ОБРАБОТАННЫХ кадров трекер держит потерянного человека.
    # Умолчание — значение из штатного botsort.yaml; проверено по исходнику
    # ultralytics: `max_frames_lost = args.track_buffer`, без пересчёта по
    # частоте кадров и без предела сверху. Отсюда главное следствие: величина
    # задана в кадрах, значит при шаге 3 это три секунды, а при шаге 1 — одна.
    # Меняя шаг, число надо менять вместе с ним, иначе память поедет молча.
    track_buffer: int = DEFAULT_TRACK_BUFFER
    # Узнавать ли человека по внешности, а не только по координате. В штатном
    # botsort.yaml выключено. Решения 057 и 058 замерили, что следы у дверей
    # теряются не разрывом и не склейкой рамок, а тем, что человека закрывают:
    # координата после перекрытия бесполезна, вид — нет. Цена — время детекции.
    with_reid: bool = False
    # Ворота узнавания. Инертны без `with_reid`, поэтому в ключ кэша входят
    # только вместе с ним: иначе имена кэшей менялись бы от величины, которая
    # на треки не влияет вовсе.
    proximity_thresh: float = DEFAULT_PROXIMITY_THRESH
    appearance_thresh: float = DEFAULT_APPEARANCE_THRESH

    def memory_seconds(self, fps: float) -> float:
        """Память трекера в секундах записи — величина, которая имеет смысл."""
        return self.track_buffer * self.stride / fps

    def tag(self) -> str:
        """Ключ кэша. Память дописывается, только когда отличается от штатной.

        Иначе появление поля переименовало бы КАЖДЫЙ уже посчитанный кэш, хотя
        треки в них не изменились, — и боевые записи пришлось бы прогонять
        заново без всякой причины.
        """
        tag = (
            f"{Path(self.weights).stem}_{self.imgsz}_"
            f"{Path(self.tracker).stem}_s{self.stride}_c{self.conf}"
        )
        if self.track_buffer != DEFAULT_TRACK_BUFFER:
            tag += f"_b{self.track_buffer}"
        if self.with_reid:
            tag += "_reid"
            if self.proximity_thresh != DEFAULT_PROXIMITY_THRESH:
                tag += f"p{self.proximity_thresh}"
            if self.appearance_thresh != DEFAULT_APPEARANCE_THRESH:
                tag += f"a{self.appearance_thresh}"
        return tag


DETECTOR = DetectorSettings()

# Боевая запись может идти часами. Полный stride=1 там — часы детекции внутри
# обычного `git push`, потому что гейты (doors jitter, baseline) вызываются на
# каждый push автоматически. stride входит в DetectorSettings.tag() и потому в
# ключ кэша (core/trackdata.cache_path), поэтому боевой и тестовый кэш не
# путаются между собой.
PROD_STRIDE = 3

# Стенд считает не весь файл, а шесть окон стоянок по 50 с — довод про «часы
# внутри git push» к нему не относится, и там кадры смотрятся подряд. Память
# трекера поднимается вместе с шагом: 90 кадров при шаге 1 — это те же три
# секунды, что 30 кадров при шаге 3 у боевого пути. Это не ослабление сшивки
# (запрет 5), а удержание величины постоянной при смене единицы.
BENCH_STRIDE = 1
BENCH_TRACK_BUFFER = 90


def detector_for(video: Path) -> DetectorSettings:
    """Настройки детектора для конкретного видео — единственный их источник.

    Разъехавшиеся копии этого выбора (одно место читает кэш с одним stride,
    другое — с другим) и есть тот дефект, из-за которого гейт публикации решил
    бы, что кэша нет, и запустил детекцию заново поверх уже готового кэша.
    """
    if _is_under(video, PROD_VIDEO_DIR):
        return dataclasses.replace(DETECTOR, stride=PROD_STRIDE)
    return DETECTOR


def _is_under(path: Path, directory: Path) -> bool:
    try:
        return path.resolve().is_relative_to(directory.resolve())
    except (OSError, ValueError):
        return False


def cache_ready(video: Path) -> bool:
    """Готов ли кэш под настройки, которые получит именно это видео.

    Несуществующий файл кэша заведомо не имеет: `content_hash` внутри
    `cache_path` требует прочитать файл и упал бы там, где ответ и так ясен.
    """
    if not video.exists():
        return False
    from .core.trackdata import cache_path

    return cache_path(video, detector_for(video)).exists()


def prod_cache_missing(video: Path) -> bool:
    """Боевая запись без готового кэша.

    Гейты вызываются автоматически на каждый push — если для боевой записи
    кэша ещё нет, они не должны САМИ запускать детекцию: на многочасовом видео
    это часы работы внутри обычного git push. Тестовые ролики сюда не попадают:
    они малы, и первый прогон на них — ожидаемая часть обычной работы, а не
    риск, от которого нужно защищаться.
    """
    return _is_under(video, PROD_VIDEO_DIR) and not cache_ready(video)


