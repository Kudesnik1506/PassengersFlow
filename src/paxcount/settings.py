def videos_in(target: Path | None) -> list[Path]:
    """Видео по пути: сам файл, всё подходящее в дереве или оба набора сразу.

    ``None`` означает «весь материал»: боевой набор, затем отладочный.
    Отсутствующая папка пропускается — боевой съёмки может ещё не быть, и это
    не повод падать.

    Обход рекурсивный, потому что смена приходит деревом: оператор отдаёт её
    как `видео 1/Камера 1/Утро/*.MP4`. Плоский обход не видел там ничего, а
    гейт `pre-push` в это же время рапортовал «видео есть» по отладочным
    роликам и признавал набор проверенным.
    """
    if target is None:
        return [v for d in VIDEO_DIRS if d.is_dir() for v in videos_in(d)]
    if target.is_dir():
        return sorted(
            p
            for p in target.rglob("*")
            # Точка в начале имени — служебное, а не запись: на внешнем томе
            # macOS сама заводит спутников `._имя.mp4`, и каждый стал бы
            # «видео», которое не открывается.
            if p.suffix.lower() in VIDEO_SUFFIXES
            and not any(part.startswith(".") for part in p.relative_to(target).parts)
        )
    # Несуществующий путь раньше возвращался как «одно видео с таким именем» и
    # шёл дальше по конвейеру, где падал невнятно. Живой случай: запущенный
    # веб-UI держал в памяти путь к папке, которую переименовали, и отдавал 500
    # вместо сообщения о том, чего именно нет.
    if not target.exists():
        raise FileNotFoundError(f"нет такого видео или папки: {target}")
    return [target]
