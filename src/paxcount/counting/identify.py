"""Промпт опознания: что за машина приехала на остановку.

Второй промпт проекта, и правила у него обратны первому. Счётному
(`prompt.py`) читать номера запрещено — ему нужны люди, а номер в его ответе
лишний. Здесь номер и есть работа: заказчик пишет «Госномера пишем
обязательно», это колонка G бланка.

Опознание идёт по кадру, выбранному детектором — тому, где рамка ТС крупнее
всего (решение 028). Брать кадр по времени из выгрузки оператора нельзя:
слепой замер показал, что так в девяти случаях из десяти читается соседняя
машина, и ошибка выглядит как успех.

Наполненность этот промпт не спрашивает (решение 032). Колонку I заполняет
выгрузка оператора, где строка в ней есть; своей моделью наполненность не
меряем — читаемость салона сквозь стекло с К2/К3 не измерена, а колонка не
обязательна так, как госномер.

Про отказ. Замер по госномеру: с кадра прочиталось `Р750НЕ178`, портал знает
`Р750НЕ198` — буквы и цифры верны, регион выдуман. В готовом файле такую
ошибку не увидеть, поэтому регион требуется либо прочитать, либо не писать.
"""

from __future__ import annotations

import json
import re
from dataclasses import dataclass, replace

from ..core.majority import strict

# Ответ заказчика от 2026-09-15: размер определяется числом дверей, а у
# рельсового транспорта — числом гармошек между вагонами.
SIZE_RULES = """\
Размер колёсного ТС — по числу дверей с той стороны, где посадка:
две двери — «Средний», три — «Большой», четыре и гармошка — «Особо большой».
Размер трамвая — по гармошкам: без гармошки «Один вагон», одна гармошка
«Два вагона», две гармошки «Три вагона».\
"""

# Боевой кадр показал цену узкой подсказки: оба прогона написали «табло
# тёмное, номер не разобрать», а маршрут был нанесён трафаретом на двери.
# Машину опознали по борту через портал, маршрут потеряли на ровном месте.
_WHERE_TO_LOOK = """\
Номер маршрута ищется не только на табло над лобовым стеклом: его наносят
трафаретом на дверь или борт, кладут табличкой в лобовое стекло и клеят
наклейкой в окне салона. Светодиодное табло на кадре часто срезано строчной
развёрткой камеры — тогда смотрите остальные места.

Бортовой номер — крупные цифры на кузове сбоку или на передней маске; он
бывает выцветшим, но читается. Не путать его с государственным.\
"""

_HONESTY = """\
Читать только то, что видно. Если номер, буква или цифра не различимы —
оставить поле пустым и сказать об этом в "doubts". Особо это касается региона
в государственном номере (последние две-три цифры): 178 и 198 в Петербурге
встречаются оба, и догадка здесь неотличима от чтения. Пустое поле проверяемо,
выдуманное — нет.\
"""

_PRIVACY = """\
Не описывать лица, одежду и приметы людей. Номера транспорта читать нужно,
приметы пассажиров — нет.\
"""

_ANSWER = """\
Ответ — только JSON, без пояснений вокруг:
{"kind": "Автобус"|"Троллейбус"|"Трамвай"|null,
 "board_number": "<бортовой номер на кузове или лобовой панели, или null>",
 "state_number": "<государственный номер, или null>",
 "route": "<номер маршрута с табло, или null>",
 "size": "<Средний|Большой|Особо большой|Один вагон|Два вагона|Три вагона|null>",
 "doubts": "<что осталось неясным, или пустая строка>"}\
"""

_ANSWER_NO_SIZE = """\
Ответ — только JSON, без пояснений вокруг:
{"kind": "Автобус"|"Троллейбус"|"Трамвай"|null,
 "board_number": "<бортовой номер на кузове или лобовой панели, или null>",
 "state_number": "<государственный номер, или null>",
 "route": "<номер маршрута с табло, или null>",
 "doubts": "<что осталось неясным, или пустая строка>"}\
"""


def build_identify_prompt(ask_size: bool = True) -> str:
    """Собирает промпт опознания для кадра, выбранного по треку ТС.

    `ask_size=False` — для камеры, которая снимает машину со стороны без
    дверей. Размер определяется их числом, и с камеры 1 ответ о нём был бы
    выдумкой: она стоит навстречу потоку и видит морду и левый борт
    (решение 030).
    """
    parts = [
        "Перед вами кадр с камеры на остановке общественного транспорта "
        "Санкт-Петербурга. В кадре транспортное средство, подъехавшее к "
        "остановке.",
        "Задача: определить, что это за машина. Нужны бортовой номер "
        "(его пишут крупно на кузове или на лобовой панели), государственный "
        "номер с бампера, номер маршрута"
        + (", вид и размер ТС." if ask_size else " и вид ТС."),
        _WHERE_TO_LOOK,
    ]
    if ask_size:
        parts.append(SIZE_RULES)
    parts += [_HONESTY, _PRIVACY, _ANSWER if ask_size else _ANSWER_NO_SIZE]
    return "\n\n".join(parts)


@dataclass(frozen=True)
class Identity:
    """Что один прогон разглядел на кадре. `None` — «не прочитал»."""

    kind: str | None = None
    board_number: str | None = None
    state_number: str | None = None
    route: str | None = None
    size: str | None = None
    doubts: str = ""


FIELDS = ("kind", "board_number", "state_number", "route", "size")
TITLES = {"kind": "вид ТС", "board_number": "бортовой номер",
           "state_number": "госномер", "route": "маршрут", "size": "размер"}


def parse_identity(text: str) -> Identity:
    """Достаёт ответ из того, чем модель его обрамила."""
    found = re.search(r"\{.*?\}", text or "", re.S)
    if found is None:
        raise ValueError("в ответе нет JSON — это не «пусто», а нечитаемый ответ")
    body = json.loads(found.group(0))
    clean = {f: (str(body[f]).strip() or None) if body.get(f) is not None else None
              for f in FIELDS}
    return Identity(**clean, doubts=str(body.get("doubts") or ""))


def agreed_identity(answers: list[Identity]) -> tuple[Identity, dict[str, str]]:
    """Поля строгого большинства и причина отказа по каждому спорному.

    Поля судятся порознь: прогон может прочесть крупный бортовой номер и не
    разобрать маршрут на табло. Согласия нет — поле пустое, а не «самое
    правдоподобное» (решения 040, 082).
    """
    if len(answers) < 2:
        return Identity(), {"всё": "один прогон — это мнение, а не согласие "
                                    "(решение 024)"}
    agreed, why = Identity(), {}
    for field in FIELDS:
        value, note = strict([getattr(a, field) for a in answers], TITLES[field])
        if value is None and note:
            why[field] = note
        agreed = replace(agreed, **{field: value})
    return agreed, why


def public_kind(name: str | None):
    """Вид ТС словами модели — в словарь заказчика, или `None`.

    Детектор ищет крупные кузова и приводит заодно грузовые фургоны: на боевом
    утре один такой дошёл до опознания и был бы записан строкой. Книга ведётся
    по общественному транспорту, и вид вне словаря означает, что строки нет
    вовсе. Подставить «Автобус» нельзя: графа F — утверждение, а не заглушка.
    """
    from ..delivery.model import VehicleKind

    try:
        return VehicleKind((name or "").strip())
    except ValueError:
        return None
