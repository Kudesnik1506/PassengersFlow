"""Промпт опознания: что за машина приехала на остановку.

Второй промпт проекта, и правила у него обратны первому. Счётному
(`prompt.py`) читать номера запрещено — ему нужны люди, а номер в его ответе
лишний. Здесь номер и есть работа: заказчик пишет «Госномера пишем
обязательно», это колонка G бланка.

Опознание идёт по кадру, выбранному детектором — тому, где рамка ТС крупнее
всего (решение 028). Брать кадр по времени из выгрузки оператора нельзя:
слепой замер показал, что так в девяти случаях из десяти читается соседняя
машина, и ошибка выглядит как успех.

Наполненность этот промпт не спрашивает (решение 032). Колонку I заполняет
выгрузка оператора, где строка в ней есть; своей моделью наполненность не
меряем — читаемость салона сквозь стекло с К2/К3 не измерена, а колонка не
обязательна так, как госномер.

Про отказ. Замер по госномеру: с кадра прочиталось `Р750НЕ178`, портал знает
`Р750НЕ198` — буквы и цифры верны, регион выдуман. В готовом файле такую
ошибку не увидеть, поэтому регион требуется либо прочитать, либо не писать.
"""

from __future__ import annotations

# Ответ заказчика от 2026-09-15: размер определяется числом дверей, а у
# рельсового транспорта — числом гармошек между вагонами.
SIZE_RULES = """\
Размер колёсного ТС — по числу дверей с той стороны, где посадка:
две двери — «Средний», три — «Большой», четыре и гармошка — «Особо большой».
Размер трамвая — по гармошкам: без гармошки «Один вагон», одна гармошка
«Два вагона», две гармошки «Три вагона».\
"""

_HONESTY = """\
Читать только то, что видно. Если номер, буква или цифра не различимы —
оставить поле пустым и сказать об этом в "doubts". Особо это касается региона
в государственном номере (последние две-три цифры): 178 и 198 в Петербурге
встречаются оба, и догадка здесь неотличима от чтения. Пустое поле проверяемо,
выдуманное — нет.\
"""

_PRIVACY = """\
Не описывать лица, одежду и приметы людей. Номера транспорта читать нужно,
приметы пассажиров — нет.\
"""

_ANSWER = """\
Ответ — только JSON, без пояснений вокруг:
{"kind": "Автобус"|"Троллейбус"|"Трамвай"|null,
 "board_number": "<бортовой номер на кузове или лобовой панели, или null>",
 "state_number": "<государственный номер, или null>",
 "route": "<номер маршрута с табло, или null>",
 "size": "<Средний|Большой|Особо большой|Один вагон|Два вагона|Три вагона|null>",
 "doubts": "<что осталось неясным, или пустая строка>"}\
"""


def build_identify_prompt() -> str:
    """Собирает промпт опознания для кадра, выбранного по треку ТС."""
    return "\n\n".join([
        "Перед вами кадр с камеры на остановке общественного транспорта "
        "Санкт-Петербурга. В кадре транспортное средство, подъехавшее к "
        "остановке.",
        "Задача: определить, что это за машина. Нужны бортовой номер "
        "(его пишут крупно на кузове или на лобовой панели), государственный "
        "номер с бампера, номер маршрута с табло маршрутоуказателя, вид и "
        "размер ТС.",
        SIZE_RULES,
        _HONESTY,
        _PRIVACY,
        _ANSWER,
    ])
