"""Промпт счёта: правила заказчика, запреты и форма ответа.

Правила счёта взяты из инструкции расшифровщика дословно по смыслу, а не
придуманы нами. Это важнее, чем кажется: первые слепые прогоны мы делали до
того, как увидели инструкцию, и они считали «всех людей у двери». Заказчик
считает иначе — ребёнок на руках не пассажир, а контролёр пассажир. Разойтись
здесь значит отдать неверный файл, не заметив этого, а платят за файл целиком.

Два запрета живут рядом с правилами, потому что нарушаются они одинаково легко.
Лица и номера: кадры в счётную модель уходить могут (решение 019), но приметы
людей из неё возвращаться не должны — наружу уходят только числа (решение 018).
Честный отказ: сегодняшний замер по номерам показал, что «не видно» — самый
полезный вид ошибки, потому что его видно. Догадка, выданная за наблюдение,
неотличима от правды и потому дороже.
"""

from __future__ import annotations

from ..settings import PACKAGE_FPS
from ..windows import Window

COUNTING_RULES = """\
Кого считать (правила заказчика, не наши):
- всех, кто должен платить за проезд или отмечать проездной;
- детей, которые передвигаются самостоятельно, — считать наравне со взрослыми;
- контролёров — считать.

Кого не считать:
- детей на руках у взрослого;
- детей в коляске (сама коляска тоже не человек);
- тех, кто прошёл мимо двери, не входя и не выходя;
- тех, кто стоит у транспорта и остаётся снаружи.

Каждого человека считать ровно один раз, даже если он попал в несколько кадров
или вышел и вернулся к двери.\
"""

_PRIVACY = """\
Не описывать лица, одежду и приметы людей в ответе — только числа и время.
Не читать и не выписывать государственные и бортовые номера транспорта.\
"""

_HONESTY = """\
Если событие не видно или вы не уверены — так и напишите в поле "doubts" и не
увеличивайте счёт. Догадка, выданная за наблюдение, здесь хуже пропуска:
пропуск видно, догадку — нет.\
"""

_ANSWER = """\
Ответ — только JSON, без пояснений вокруг:
{"boarded": <вошло, целое>, "alighted": <вышло, целое>,
 "events": [{"t": <секунда>, "direction": "in"|"out"}],
 "doubts": "<что осталось неясным, или пустая строка>"}\
"""


def build_count_prompt(window: Window, fps: float = PACKAGE_FPS) -> str:
    """Собирает промпт для одного окна счёта.

    Про соседние машины говорится, только когда они есть: лишнее
    предупреждение на пустом месте само по себе сбивает — модель начинает
    искать вторую машину там, где её нет.
    """
    parts = [
        "Перед вами последовательность кадров с камеры на остановке "
        "общественного транспорта.",
        f"Кадры идут подряд с частотой {fps:g} в секунду; в имени каждого кадра "
        f"указана его секунда от начала окна. Окно длится {window.duration:.0f} секунд.",
        "Задача: посчитать, сколько человек вошло в транспортное средство и "
        "сколько вышло из него за это окно.",
        COUNTING_RULES,
    ]

    if window.rivals:
        parts.append(
            "В кадре больше одного транспортного средства. Считать только тех, "
            "кто входит в обведённое рамкой ТС или выходит из него. Люди у "
            "соседней машины к нашему счёту не относятся, даже если они рядом."
        )
    if window.contested:
        parts.append(
            "Внимание: соседняя машина частично перекрывает двери нашей. Если "
            "из-за этого часть входов и выходов не видна, скажите об этом в "
            'поле "doubts" — эту запись проверит человек.'
        )

    parts += [_PRIVACY, _HONESTY, _ANSWER]
    return "\n\n".join(parts)
