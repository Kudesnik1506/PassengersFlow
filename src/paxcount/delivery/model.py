"""Строка таблицы заказчика и закрытые словари её значений.

Словари закрыты по той же причине, по какой закрыты словари гейта памяти:
открытый словарь ломает приёмку молча. «Особо большой» и «Особо большой »
с пробелом — в принятой таблице встречаются оба написания, и если их пропускать,
сводка заказчика получит два разных типа ТС вместо одного.

Модель хранит больше, чем показывает таблица, и это намеренно: бортовой номер
рядом с государственным (решение 026) и пометки о заменённых данных оператора.
Оба поля в файл заказчика не уходят — они нужны, чтобы строку можно было
перепроверить, когда её оспорят.
"""

from __future__ import annotations

from enum import Enum

from pydantic import BaseModel, Field, field_validator


class VehicleKind(str, Enum):
    """Вид ТС — словарь заказчика с листа «Тип ТС».

    «Развозка» и «Шаттл» — не размер и не марка, а назначение рейса: развозка
    везёт на работу, шаттл бесплатно к магазину. Инструкция различает их по
    табличке в лобовом стекле и по отсутствию номера маршрута.
    """

    BUS = "Автобус"
    TROLLEY = "Троллейбус"
    TRAM = "Трамвай"
    SHUTTLE_WORK = "Развозка"
    MINIBUS = "Маршрутка"
    SHUTTLE_MALL = "Шаттл"


class VehicleSize(str, Enum):
    """Размер ТС. У рельсового транспорта это вагоны, у колёсного — двери.

    Соответствие дверей размеру из таблицы 3 инструкции: одна дверь — малый
    (тип «ГАЗель»), две — средний, три — большой, четыре с гармошкой — особо
    большой. Двери видны с той же стороны, которую снимает камера на
    остановке, поэтому размер — самая дешёвая из опознавательных колонок.
    """

    SMALL = "Малый"
    MEDIUM = "Средний"
    LARGE = "Большой"
    XLARGE = "Особо большой"
    ONE_CAR = "Один вагон"
    TWO_CARS = "Два вагона"
    THREE_CARS = "Три вагона"


class Occupancy(str, Enum):
    """Наполненность по прибытию, таблица 1 инструкции. Буквы русские.

    Шкала не линейная по людям, а по видимости салона: Б — «не видно свободных
    сидячих», В — «затруднена видимость сквозь салон», Г — «салон не виден
    насквозь». Это важно для промпта: модель должна судить по заслонённости
    стекла, а не пересчитывать головы.
    """

    A = "А"
    B = "Б"
    V = "В"
    G = "Г"
    D = "Д"
    E = "Е"


# Коды комментариев из таблицы 2: какие двери не попали в кадр и можно ли по
# ним считать. 1-4 — можно, 5-8 — нельзя. Держатся здесь, а не в валидаторе,
# чтобы модель отвергала опечатку сразу, а не на выгрузке.
COMMENT_CODES = frozenset(range(1, 9))
# Коды, при которых часть людей заведомо не посчитана: двери вне кадра.
COMMENT_CODES_UNCOUNTABLE = frozenset({5, 6, 7, 8})

# Виды ТС, которым инструкция требует именно государственный номер.
# Остальным (троллейбус, трамвай) в графу идёт бортовой: госномера у них нет.
KINDS_NEEDING_STATE_NUMBER = frozenset({VehicleKind.BUS, VehicleKind.MINIBUS,
                                        VehicleKind.SHUTTLE_WORK, VehicleKind.SHUTTLE_MALL})


class DeliveryRow(BaseModel):
    """Одна строка таблицы заказчика плюс то, чем её можно перепроверить."""

    group: str
    date: str
    hours: int = Field(ge=0, le=23)
    minutes: int = Field(ge=0, le=59)
    stop: str
    kind: VehicleKind
    # Оба номера хранятся всегда. В файл заказчика уходит один — см. `number`.
    board_number: str | None = None
    state_number: str | None = None
    route: str | None = None
    occupancy: Occupancy | None = None
    size: VehicleSize | None = None
    # None — это «не считали» (правило N/A), а не ноль.
    alighted: int | None = Field(default=None, ge=0)
    boarded: int | None = Field(default=None, ge=0)
    comment: int | None = None
    video: str = ""
    operator: str = ""
    # Поля, где мы разошлись с оператором, и чем обосновались. В таблицу не
    # попадает: нужно нам, чтобы разобрать спор, а не заказчику.
    overrides: dict[str, str] = Field(default_factory=dict)

    @field_validator("comment")
    @classmethod
    def _known_comment(cls, value: int | None) -> int | None:
        if value is not None and value not in COMMENT_CODES:
            raise ValueError(
                f"код комментария {value} вне таблицы 2 инструкции (допустимы 1..8)"
            )
        return value

    @property
    def number(self) -> str | None:
        """Что уходит в графу «Бортовой или государственный номер ТС».

        У автобуса — государственный, и подставлять вместо него бортовой
        нельзя: заказчик пишет «Госномера пишем обязательно», а подстановка
        выглядела бы как выполненное требование. Отсутствие — пустая графа,
        видимая при проверке.
        """
        if self.kind in KINDS_NEEDING_STATE_NUMBER:
            return self.state_number
        return self.board_number

    @property
    def counted(self) -> bool:
        """Был ли счёт вообще. Ноль — был, N/A — не был."""
        return self.alighted is not None and self.boarded is not None
