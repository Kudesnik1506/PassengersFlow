"""Строка таблицы заказчика и закрытые словари её значений.

Словари закрыты по той же причине, по какой закрыты словари гейта памяти:
открытый словарь ломает приёмку молча. «Особо большой» и «Особо большой »
с пробелом — в принятой таблице встречаются оба написания, и если их пропускать,
сводка заказчика получит два разных типа ТС вместо одного.

Модель хранит больше, чем показывает таблица, и это намеренно: бортовой номер
рядом с государственным (решение 026) и пометки о заменённых данных оператора.
Оба поля в файл заказчика не уходят — они нужны, чтобы строку можно было
перепроверить, когда её оспорят.
"""

from __future__ import annotations

from datetime import datetime
from enum import Enum

from pydantic import BaseModel, Field, field_validator


class VehicleKind(str, Enum):
    """Вид ТС — словарь заказчика с листа «Тип ТС».

    «Развозка» и «Шаттл» — не размер и не марка, а назначение рейса: развозка
    везёт на работу, шаттл бесплатно к магазину. Инструкция различает их по
    табличке в лобовом стекле и по отсутствию номера маршрута.
    """

    BUS = "Автобус"
    TROLLEY = "Троллейбус"
    TRAM = "Трамвай"
    SHUTTLE_WORK = "Развозка"
    MINIBUS = "Маршрутка"
    SHUTTLE_MALL = "Шаттл"


class VehicleSize(str, Enum):
    """Размер ТС. У рельсового транспорта это вагоны, у колёсного — двери.

    Соответствие дверей размеру из таблицы 3 инструкции: одна дверь — малый
    (тип «ГАЗель»), две — средний, три — большой, четыре с гармошкой — особо
    большой. Двери видны с той же стороны, которую снимает камера на
    остановке, поэтому размер — самая дешёвая из опознавательных колонок.
    """

    SMALL = "Малый"
    MEDIUM = "Средний"
    LARGE = "Большой"
    XLARGE = "Особо большой"
    ONE_CAR = "Один вагон"
    TWO_CARS = "Два вагона"
    THREE_CARS = "Три вагона"


# Соответствие размера числу дверей у колёсного ТС (таблица 3 инструкции),
# было прозой в докстрине выше и нигде не читалось кодом. Нужно как источник
# правды для арифметической проверки разметки дверей (`paxcount.truth`):
# пропущенная дверь у 7861 (три двери по размеру, две в разметке) нашлась
# только когда это сравнение стало явным. Рельсовый транспорт сюда не входит:
# там размер — число вагонов по гармошкам, а не дверей.
DOORS_BY_SIZE: dict[VehicleSize, int] = {
    VehicleSize.SMALL: 1,
    VehicleSize.MEDIUM: 2,
    VehicleSize.LARGE: 3,
    VehicleSize.XLARGE: 4,
}


class Occupancy(str, Enum):
    """Наполненность по прибытию, таблица 1 инструкции. Буквы русские.

    Своей моделью не считается (решение 032): колонку заполняет только
    выгрузка оператора, где строка для неё есть. Читаемость салона сквозь
    стекло с К2/К3 не измерена, а колонка не обязательна так, как госномер —
    строить для неё отдельный счёт не стали.
    """

    A = "А"
    B = "Б"
    V = "В"
    G = "Г"
    D = "Д"
    E = "Е"


# Коды комментариев из таблицы 2: какие двери не попали в кадр и можно ли по
# ним считать. 1-4 — можно, 5-8 — нельзя. Держатся здесь, а не в валидаторе,
# чтобы модель отвергала опечатку сразу, а не на выгрузке.
COMMENT_CODES = frozenset(range(1, 9))
# Коды, при которых часть людей заведомо не посчитана: двери вне кадра.
COMMENT_CODES_UNCOUNTABLE = frozenset({5, 6, 7, 8})

# Виды ТС, которым инструкция требует именно государственный номер.
# Остальным (троллейбус, трамвай) в графу идёт бортовой: госномера у них нет.
KINDS_NEEDING_STATE_NUMBER = frozenset({VehicleKind.BUS, VehicleKind.MINIBUS,
                                        VehicleKind.SHUTTLE_WORK, VehicleKind.SHUTTLE_MALL})


class DeliveryRow(BaseModel):
    """Одна строка таблицы заказчика плюс то, чем её можно перепроверить."""

    group: str
    date: str
    hours: int = Field(ge=0, le=23)
    minutes: int = Field(ge=0, le=59)
    stop: str
    kind: VehicleKind
    # Оба номера хранятся всегда. В файл заказчика уходит один — см. `number`.
    board_number: str | None = None
    state_number: str | None = None
    route: str | None = None
    occupancy: Occupancy | None = None
    size: VehicleSize | None = None
    # None — это «не считали» (правило N/A), а не ноль.
    alighted: int | None = Field(default=None, ge=0)
    boarded: int | None = Field(default=None, ge=0)
    comment: int | None = None
    # Аномалии съёмки словами: разрыв записи, край смены и прочее, что заказчик
    # требует отражать в комментариях (17.09). Отдельно от кода, потому что код
    # проверяем по таблице 2, а текст — нет; склеивает их `comment_cell`.
    notes: tuple[str, ...] = ()
    video: str = ""
    operator: str = ""
    # Камера, на которой видна посадка-высадка, и что показывали ЕЁ часы в этот
    # момент. Время бланка стоит на общей шкале (решение 036), а перематывать
    # запись будут по часам самой камеры, и они с общей шкалой не совпадают:
    # К3 отстаёт от К2 почти на семь минут. Пусто — посадку мы не видели.
    camera: str = ""
    camera_ts: datetime | None = None
    # Откуда взялось наше значение: «портал по борту 1596», «смена выбрана по
    # времени». Это происхождение, а не спор, и в книгу оно не идёт — там о
    # нашем авторстве говорит цвет (принцип 9). Нужно нам, чтобы разобрать
    # спор, если заказчик оспорит строку.
    overrides: dict[str, str] = Field(default_factory=dict)
    # То, с чем мы НЕ СОГЛАСНЫ и не вправе исправить молча: невозможная пара
    # «вид + размер», размер против числа дверей, маршрут портала против
    # маршрута строки. Уходит в книгу графой S (решение 087).
    #
    # Отдельно от `overrides` не ради порядка: первая же боевая сборка залила
    # графу S на 292 строках из 295 пометками об удачной подстановке номера.
    # Графа, заполненная почти везде, не говорит ничего — это тот самый провал,
    # который заказчик отменил в решении 070.
    disagreements: dict[str, str] = Field(default_factory=dict)

    @field_validator("comment")
    @classmethod
    def _known_comment(cls, value: int | None) -> int | None:
        if value is not None and value not in COMMENT_CODES:
            raise ValueError(
                f"код комментария {value} вне таблицы 2 инструкции (допустимы 1..8)"
            )
        return value

    @property
    def comment_cell(self) -> str | None:
        """Графа M целиком: код таблицы 2 и аномалии съёмки словами.

        `None` — сказать нечего, и графа остаётся пустой. Так в принятом
        заказчиком файле: неизвестное и отсутствующее там не подписывается
        словами, а просто пусто.
        """
        parts = ([str(self.comment)] if self.comment is not None else []) + list(self.notes)
        return "; ".join(parts) if parts else None

    @property
    def disagreement_cell(self) -> str | None:
        """Графа S: всё, с чем мы не согласны, словами и с именем графы.

        Имя графы обязательно: «портал говорит 64» без слова «маршрут» читателю
        ничего не говорит, а читать это будет человек построчно.

        Порядок по имени графы, а не по порядку появления: книга пересобирается
        по многу раз за день, и переставленные местами сообщения выглядели бы
        правкой, которой не было.

        `None` — спорить не о чем, и графа пуста. Это норма: несогласие
        случается на девяти строках из трёхсот.
        """
        parts = [f"{field}: {why}"
                  for field, why in sorted(self.disagreements.items())]
        return "; ".join(parts) if parts else None

    @property
    def camera_cell(self) -> str:
        """Графа P: какая камера и что на её часах.

        Только часы, минуты и секунды: у К3 в именах файлов стоит август вместо
        сентября (`clocks`), и чужой месяц в книге читался бы как ошибка книги,
        а не как дефект камеры. На вопрос «куда перемотать» дата не отвечает —
        запись названа в графе N.
        """
        if not self.camera or self.camera_ts is None:
            return ""
        return f"К{self.camera} {self.camera_ts:%H:%M:%S}"

    @property
    def number(self) -> str | None:
        """Что уходит в графу «Бортовой или государственный номер ТС».

        У автобуса — государственный; нет его — бортовой. Графа так и названа,
        и в принятом заказчиком файле она заполнена во всех 312 строках: у 243
        автобусов госномер, у восьми бортовой («7364 - нет в базе», «7417»), у
        60 троллейбусов бортовой всегда.

        Пустая графа не строже требования «госномера пишем обязательно», а
        беднее: заказчик теряет единственный ключ, по которому машину можно
        найти в справочнике. Подстановка при этом не выдаёт себя за успех —
        правило приёмки смотрит на `state_number`, а не на эту графу, и о
        недостающем госномере сообщает по-прежнему (решение 071).
        """
        if self.kind in KINDS_NEEDING_STATE_NUMBER:
            return self.state_number or self.board_number
        return self.board_number

    @property
    def counted(self) -> bool:
        """Был ли счёт вообще. Ноль — был, N/A — не был."""
        return self.alighted is not None and self.boarded is not None
