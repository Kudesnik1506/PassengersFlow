"""Что должно быть на руках, чтобы начинать сборку книги.

Требование владельца (18.09): входные данные спрашиваются, а не угадываются.
Умолчание здесь однажды уже уехало к заказчику — в поставке оказались чужая
группа ОП и чужая фамилия расшифровщика, подставленные из тестовой заготовки, и
заметил это не код, а человек.

Отказ устроен по двум правилам:

* **называть всё сразу.** Отказ по одному входу — это пять запусков подряд
  вместо одного разговора;
* **говорить словами заказчика.** «--group не задан» ничего не значит для
  человека, который держит перед глазами папку с работой.

Постоянное сюда не входит. Инструкция, шаблон, принятый образец и фамилия
расшифровщика не меняются от работы к работе: первые три лежат в репозитории,
фамилия — в настройке рядом с учёткой портала. В публичный репозиторий она не
попадает (решение 016): это имя живого человека.
"""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path
from typing import Mapping

DECODER_ENV = "DECODER_NAME"


@dataclass(frozen=True)
class Inputs:
    """Переменная часть работы — то, что приходит с каждой новой остановкой."""

    group: str
    stop: str
    operator_export: Path | None
    videos: Path | None
    template: Path | None
    # Камеры, для которых задано направление движения. Пустой набор означает,
    # что нос кузова определять нечем, а зеркальный код 5↔7 уходит заказчику
    # правдоподобным и неверным.
    cameras: tuple[str, ...]


def missing(inputs: Inputs) -> list[str]:
    """Чего не хватает, чтобы начинать. Пустой список — можно работать.

    Путь мимо несуществующего файла считается отсутствием данных, а не их
    наличием: чаще всего это опечатка в пути, и собранная «книга по пустой
    выгрузке» выглядит как обычная книга.
    """
    gaps: list[str] = []
    if not inputs.group.strip():
        gaps.append("группа ОП — она идёт в графу A бланка")
    if not inputs.stop.strip():
        gaps.append("номер ОП — по нему отбираются записи оператора")
    if not _there(inputs.operator_export):
        gaps.append("выгрузка оператора — без неё книга не лента смены, "
                     "а выборка расшифрованных машин")
    if not _there(inputs.videos):
        gaps.append("видеозаписи — по ним идут детекция, часы и графа файла")
    if not inputs.cameras:
        gaps.append("направление движения на снимающих камерах — без него "
                     "неизвестно, какой конец кузова срезан кадром")
    if not _there(inputs.template):
        gaps.append("шаблон заказчика — книга пишется по нему: без него "
                     "пропадают выпадающие списки, пометки цветом и защита "
                     "ручного ввода")
    return gaps


def _there(path: Path | None) -> bool:
    return path is not None and path.exists()


def decoder_name(explicit: str, env: Mapping[str, str]) -> str:
    """Фамилия расшифровщика: из настройки, а явная — важнее настройки.

    Выдумывать нельзя: графа O обязательна по приёмке, и пустая графа честнее
    чужой фамилии — в поставку однажды ушла именно чужая.
    """
    named = (explicit or "").strip()
    if named:
        return named
    stored = (env.get(DECODER_ENV) or "").strip()
    if stored:
        return stored
    raise ValueError(
        f"не назван расшифровщик: графа O обязательна по приёмке. "
        f"Положите имя в {DECODER_ENV} рядом с учёткой портала "
        f"или назовите его ключом --operator"
    )
