"""Какие клетки книги красятся жёлтым по итогу сверки с оператором.

Пометка отвечает проверяющему на один вопрос: где смотреть кадр. Отсюда её
величина — по величине утверждения, а не по числу пустых граф (решение 070):

* **записи у оператора нет** — спорна вся строка. Машину видели только мы,
  второго свидетельства нет ни в одном поле, и покрасить одну графу из
  пятнадцати значило бы указать не туда;
* **запись есть, разошлось поле** — красится эта клетка, и только она. Залить
  из-за неё всю машину значит заставить искать спор там, где его нет;
* **сошлось** — не красится ничего.

Правило живёт здесь, а не в сборщике: это утверждение о книге, и проверять его
надо тестом, а не глазами на боевой выгрузке.
"""

from __future__ import annotations

from .agreement import Agreement
from .fill import COLUMNS

# Поле сверки → графа бланка. Время сюда не входит: момент разложен в бланке на
# часы и минуты, и одно расхождение даёт две клетки.
FIELD_COLUMN = {"kind": "F", "route": "H", "size": "J", "board": "G"}
TIME_COLUMNS = {"C", "D"}


def marks_for(agreement: Agreement) -> set[str]:
    """Графы бланка, которые надо покрасить по итогу сверки одной строки."""
    if agreement.missing:
        return set(COLUMNS)
    marks = {FIELD_COLUMN[f] for f in agreement.mismatched if f in FIELD_COLUMN}
    if "time" in agreement.mismatched:
        marks |= TIME_COLUMNS
    return marks
