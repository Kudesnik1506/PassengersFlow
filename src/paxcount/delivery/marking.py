"""Какие клетки книги красятся жёлтым по итогу сверки с оператором.

Правило одно и записано принципом 9 в PRINCIPLES.md: красится всякая клетка,
чьё содержимое получено нашим расчётом и отличается от записи оператора, —
независимо от того, насколько подмена бесспорна. Здесь оно превращается в
графы бланка.

Пометка отвечает проверяющему на один вопрос: где смотреть кадр. Отсюда её
величина — по величине утверждения, а не по числу пустых граф (решение 070):

* **записи у оператора нет** — спорна вся строка. Машину видели только мы,
  второго свидетельства нет ни в одном поле, и покрасить одну графу из
  пятнадцати значило бы указать не туда;
* **запись есть, разошлось поле** — красится эта клетка, и только она. Залить
  из-за неё всю машину значит заставить искать спор там, где его нет;
* **сошлось** — не красится ничего.

Правило живёт здесь, а не в сборщике: это утверждение о книге, и проверять его
надо тестом, а не глазами на боевой выгрузке.
"""

from __future__ import annotations

from .agreement import Agreement
from .fill import COLUMNS

# Поле сверки → графа бланка. Время сюда не входит: момент разложен в бланке на
# часы и минуты, и одно расхождение даёт две клетки.
# `board` — расхождение по бортовому номеру, `number` — графа номера как она
# напечатана: в ней бортовой уступает место государственному (решение 076), и
# эта подстановка — наша правка чужой графы.
FIELD_COLUMN = {"kind": "F", "route": "H", "size": "J", "board": "G",
                 "number": "G"}
TIME_COLUMNS = {"C", "D"}


def marks_for(agreement: Agreement) -> set[str]:
    """Графы бланка, которые надо покрасить по итогу сверки одной строки."""
    if agreement.missing:
        return set(COLUMNS)
    marks = {FIELD_COLUMN[f] for f in agreement.mismatched if f in FIELD_COLUMN}
    if "time" in agreement.mismatched:
        marks |= TIME_COLUMNS
    return marks


def marks_for_shifted_time(row, record) -> set[str]:
    """Графы времени строки оператора, если поправка часов переставила минуту.

    Строку оператора мы не расшифровывали, но время в ней уже не его: записи
    переводятся на общую шкалу измеренной поправкой (решение 067), иначе лента
    собралась бы из двух шкал разом. Поправка в секундах, а бланк хранит часы и
    минуты, поэтому у большинства строк число в графе не меняется — а у тех,
    где секунды перевалили через минуту, в графах C и D стоит НАШЕ число,
    отличное от записанного оператором.

    Красится оно по принципу 9 наравне с прочим нашим: заказчик сверяет книгу с
    выгрузкой построчно, и клетка без пометки означает для него «это ваше, я его
    не трогал». Величина здесь — одна минута, но молчаливая подмена времени
    отправляет искать машину не в ту минуту записи.

    Сравнение идёт по тем же двум числам, что уходят в бланк, а не по моменту:
    секунды в книгу не попадают, и расхождение в них ничего не утверждает.
    """
    if record is None or row.hours is None or row.minutes is None:
        return set()
    written = record.created
    if (int(row.hours), int(row.minutes)) == (written.hour, written.minute):
        return set()
    return set(TIME_COLUMNS)


def marks_for_repair(fields: frozenset[str]) -> set[str]:
    """Графы, починенные нами за оператором, — их книга тоже красит.

    Строка оператора, которую мы не расшифровывали, жёлтой не бывает: она
    целиком его. Но клетка, которую мы в ней исправили, уже наша, и молчать о
    ней нельзя — заказчик сверяет книгу с выгрузкой и обязан понимать, чья
    правка перед ним.
    """
    return {FIELD_COLUMN[f] for f in fields if f in FIELD_COLUMN}


def marks_for_duplicate() -> set[str]:
    """Графы строки, которую мы считаем повторным нажатием, — вся строка.

    Лишняя здесь не ячейка, а машина: её записали дважды (решение 075).
    Покрасить одну графу значило бы сказать, что спорна она, и отправить
    искать ошибку в номере или маршруте, где всё верно.
    """
    return set(COLUMNS)


# Графы, которые заполняет только наше измерение: счёт по дверям и код таблицы
# 2, выведенный из нашей разметки. Остальное в строке — опознание, и оно либо
# от оператора, либо сверено с ним.
#
# Счёт стоит в НАШИХ графах Q и R, а не в графах заказчика K и L: их он
# заполняет рукой (решение 085). Чужую графу мы не красим по той же причине,
# по которой не заполняем, — мы её не трогали.
COUNT_COLUMNS = {"Q", "R"}
COMMENT_COLUMN = "M"
# Графа P у оператора не существует вовсе — она целиком наша, и метится не за
# расхождение, а за происхождение (принцип 9). Полагаться на подпись столбца
# нельзя: заказчик читает книгу построчно, а не по шапке.
CAMERA_COLUMN = "P"
# Графа имени файла тоже наша: у оператора нет ни файла, ни камеры — он жмёт
# кнопку на остановке. «Машину искать здесь» — наше утверждение целиком.
VIDEO_COLUMN = "N"
# Фамилия расшифровщика: у оператора на остановке нет ни её, ни этой графы.
# Была единственной нашей графой без пометки происхождения — принцип 9
# исключений не знает.
DECODER_COLUMN = "O"
# Графа расхождений: всё, с чем мы не согласны. Наша целиком и по
# происхождению, и по смыслу — спорим в ней мы (решение 087).
DISAGREEMENT_COLUMN = "S"


def marks_for_our_measurement(row) -> set[str]:
    """Графы строки, заполненные нашим измерением.

    Машина, нашедшаяся у оператора, выглядит в книге как все остальные: вид,
    маршрут, размер и борт — его. Наше в ней только то, чего у него нет вовсе:
    счёт, комментарий, файл записи, часы камеры, фамилия и расхождения. В ленте
    из трёхсот строк эти клетки не найти, хотя ради них всё и делается.

    Метится заполненная графа, а не сама возможность её заполнить: `None` в
    счёте — не измерение, а его отсутствие.
    """
    marks = set(COUNT_COLUMNS) if row.counted else set()
    # По содержимому графы, а не по коду: разрыв записи попадает туда словами,
    # кода у него нет, а сказали это всё равно мы.
    if row.comment_cell:
        marks.add(COMMENT_COLUMN)
    if row.camera_cell:
        marks.add(CAMERA_COLUMN)
    if row.video:
        marks.add(VIDEO_COLUMN)
    if row.operator:
        marks.add(DECODER_COLUMN)
    if row.disagreement_cell:
        marks.add(DISAGREEMENT_COLUMN)
    return marks
